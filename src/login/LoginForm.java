    // add gif to a panel
    private void setupAnimatedBackground() {
    try {
        ImageIcon gifIcon = new ImageIcon(getClass().getResource("/InventoryImages/outbound.gif"));
        
        // Create a label that fills the entire panel
        JLabel backgroundLabel = new JLabel(gifIcon) {
            @Override
            protected void paintComponent(Graphics g) {
                // Scale the image to fill the entire label
                Image img = ((ImageIcon) getIcon()).getImage();
                g.drawImage(img, 0, 0, getWidth(), getHeight(), this);
            }
        };
        
        // Make it fill the entire panel
        backgroundLabel.setBounds(0, 0, WelcomPanel2.getWidth(), WelcomPanel2.getHeight());
        
        // Add background label first (bottom layer)
        WelcomPanel2.add(backgroundLabel);
        WelcomPanel2.setComponentZOrder(backgroundLabel, WelcomPanel2.getComponentCount() - 1);
        
        // Make all existing labels transparent
        for (Component comp : WelcomPanel2.getComponents()) {
            if (comp instanceof JLabel && comp != backgroundLabel) {
                ((JLabel) comp).setOpaque(false);
            }
        }
        
        // Force repaint
        WelcomPanel2.revalidate();
        WelcomPanel2.repaint();
        
    } catch (Exception e) {
        e.printStackTrace();
    }
}

