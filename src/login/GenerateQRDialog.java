    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
        // TODO add your handling code here:
        

    String username = txtUsername.getText();
    String password = txtPassword.getText();
    String fullname = txtFullName.getText();
    String secret = txtSecretCode.getText(); // random unique code
    String role = txtRole.getText();

    try {
        // --- 1. Create QR JSON (NO PASSWORD inside QR) ---
        JSONObject obj = new JSONObject();
        obj.put("username", username);
        obj.put("secret", secret);   // only secret, no password
        obj.put("role", role);
        String qrData = obj.toString();

        // --- 2. Generate QR Image ---
        int size = 300;
        BitMatrix matrix = new MultiFormatWriter()
                .encode(qrData, BarcodeFormat.QR_CODE, size, size);

        // Save file (optional)
            String path = "C:\\Users\\ADMIN\\Desktop\\Virdha\\Virdha Personal\\Java Projects\\NetBeans Projects\\InventoryQRSystem\\QR Code Generation\\";
        String fileName = username + "_loginQR.png";
        Path filePath = Paths.get(path + fileName);
        MatrixToImageWriter.writeToPath(matrix, "PNG", filePath);

        // Convert QR to bytes
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        MatrixToImageWriter.writeToStream(matrix, "PNG", baos);
        byte[] qrBytes = baos.toByteArray();

        // --- 3. SAVE FULL USER DETAILS IN DB ---
        try (Connection con = DBConnection.getConnection()) {

            String sql = "INSERT INTO qr_users "
                    + "(username, password, fullname, role, secret, qr_image) "
                    + "VALUES (?, ?, ?, ?, ?, ?)";

            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, username);
            pst.setString(2, password);
            pst.setString(3, fullname);
            pst.setString(4, role);
            pst.setString(5, secret);
            pst.setBytes(6, qrBytes);

            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this, 
                "QR Generated & Stored in Database Successfully!");

        this.dispose();

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }


    }//GEN-LAST:event_btnGenerateActionPerformed

