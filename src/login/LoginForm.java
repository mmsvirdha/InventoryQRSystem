    private void btnLoadQRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadQRActionPerformed
        // TODO add your handling code here:
        
    // Ask for username first
    String username = JOptionPane.showInputDialog(this, "Enter Username:");

    if (username == null || username.trim().isEmpty()) {
        return; // user cancelled or empty
    }

    try (Connection con = DBConnection.getConnection()) {

        // Fetch stored secret code from DB
        String sql = "SELECT secret FROM qr_users WHERE username = ?";
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, username.trim());
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            String storedSecret = rs.getString("secret");

            // Ask user to enter the secret code
            String inputSecret = JOptionPane.showInputDialog(this, "Enter Secret Code:");

            if (inputSecret != null && inputSecret.equals(storedSecret)) {
    // Successful login
    JOptionPane.showMessageDialog(this, "Login Successful! "  + username);

    // Get role from qr_users table
    String roleSql = "SELECT role FROM qr_users WHERE username=?";
    PreparedStatement pstRole = con.prepareStatement(roleSql);
    pstRole.setString(1, username);
    ResultSet rsRole = pstRole.executeQuery();

    String role = "User"; // default role
    if (rsRole.next()) {
        role = rsRole.getString("role");
    }
 
    // Open Dashboard with correct role
    Dashboard dashboardFrame = new Dashboard(username, role);
    TransitionHelper.fadeToFrame(this, dashboardFrame, 200);

            } else {
                JOptionPane.showMessageDialog(this, "Incorrect Secret Code!");
            }

        } else {
            JOptionPane.showMessageDialog(this, "Username not found!");
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Database error occurred.");
    }


        
    }//GEN-LAST:event_btnLoadQRActionPerformed

