private void startCamera() {
    try {
        webcam = Webcam.getDefault();
        webcam.setViewSize(WebcamResolution.QVGA.getSize());

        WebcamPanel webPanel = new WebcamPanel(webcam);
        webPanel.setFPSDisplayed(true);
        webPanel.setMirrored(true);

        panelCamera.setLayout(new java.awt.BorderLayout());
        panelCamera.add(webPanel, java.awt.BorderLayout.CENTER);

        new Thread(() -> {
            while (true) {
                try {
                    BufferedImage image = webcam.getImage();
                    if (image != null) {
                        LuminanceSource source = new BufferedImageLuminanceSource(image);
                        BinaryBitmap bitmap = new BinaryBitmap(new HybridBinarizer(source));

                        try {
                            Result result = new MultiFormatReader().decode(bitmap);

                            if (result != null) {
                                boolean valid = onQRDetected(result.getText());
                                if (valid) {
                                    break; // stop scanning thread only if QR is valid
                                }
                            }

                        } catch (NotFoundException e) {
                            // QR not found in this frame — ignore
                        }
                    }
                    Thread.sleep(100);
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }).start();

    } catch (Exception e) {
        e.printStackTrace();
    }
}



private boolean onQRDetected(String data) {
    try {
        JSONObject obj = new JSONObject(data);

        // Check if required keys exist
        if (!obj.has("username") || !obj.has("role")) {
            JOptionPane.showMessageDialog(this,
                    "Invalid QR code! Required fields missing.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return false; // invalid QR, keep scanning
        }

        String scannedUsername = obj.getString("username");
        String scannedRole = obj.getString("role");
        String scannedPassword = obj.optString("password"); // optional

        // Show success message
        JOptionPane.showMessageDialog(this,
                "<html><h2>QR Login Successful!</h2><br>" +
                "Username: " + scannedUsername + "<br>" +
                "Role: " + scannedRole + "</html>",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);

        // Valid QR → close camera and open Dashboard
        webcam.close();

        Dashboard dashboardFrame = new Dashboard(scannedUsername, scannedRole);
       
        TransitionHelper.fadeToFrame(this, dashboardFrame, 200);

        return true; // valid QR, stop scanning
        
    } catch (Exception e) {
        // Malformed JSON → show error but continue scanning
        JOptionPane.showMessageDialog(this,
                "Invalid QR code!\n" + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
        return false; // keep scanning
    }
}







